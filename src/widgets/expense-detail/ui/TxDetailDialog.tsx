type Step = "detail" | "refund" | "edit" | "split" | "recurring" | "dutch";

type Props = {
  expense: Expense;
  onClose: () => void;
  /** 폰 / 데스크톱 구분 — 표면(시트 ↔ 대화상자)은 ds 가 1280 으로 정한다. 수정 폼 부품에만 넘긴다 */
  mobile: boolean;
};

/**
 * 거래 상세 — 읽는 상세 + "더 하기" 동작 줄 (I-21 B). 1280 미만 ds Bottom Sheet · 이상 Dialog 480 한 표면 안에서
 * 상세 ↔ 환불 단계가 바뀐다(A). [수정]은 상세 위에서 수정 폼을 열고 저장하면 상세로 돌아와 응답 값으로 다시 그린다(7a).
 */
export function TxDetailDialog({
  expense: expenseProp,
  onClose,
  mobile,
}: Props) {
  const { t, i18n } = useTranslation("expense");
  const { t: tc } = useTranslation("common");
  const navigate = useNavigate();
  const snackbar = useSnackbar();
  const notifyResult = useLedgerResultToast();
  const [step, setStep] = useState<Step>("detail");
  const [confirmDelete, setConfirmDelete] = useState(false);
  const [confirmCancelRefund, setConfirmCancelRefund] = useState(false);
  const [refundDate, setRefundDate] = useState("");
  const [refundFailed, setRefundFailed] = useState(false);
  const refundMut = useRefundExpense();
  const sft = useSaveFailureText();
  const cancelRefundMut = useCancelRefund();
  const deleteMut = useDeleteExpense();
  // 부모는 목록에서 집은 **스냅샷**을 넘긴다 — 무효화가 끝나도 그 객체는 안 바뀐다. 그래서 환불 · 환불 취소 · 수정 저장의 응답으로
  // 이 자리를 갈아 열려 있는 상세가 새 값으로 다시 그려지게 한다(응답은 다시 받기가 끝난 뒤에 온다 — `invalidateFor` wait).
  const [marked, setMarked] = useState<Expense | null>(null);
  const expense = marked?.rowId === expenseProp.rowId ? marked : expenseProp;
  // 수정 폼 — 상세가 한 번 들고 같은 시트 안 한 단계로 보인다(7a · 일정 상세 `EventDetailSurface` 와 같은 구조). [수정] · [고쳐 쓰기] 때 그 거래로 갈아 끼운다
  const [editSeed, setEditSeed] = useState<{
    expense?: Expense;
    rewrite?: RewriteSeed;
  } | null>(null);
  const form = useTxForm({
    expense: editSeed?.expense,
    rewrite: editSeed?.rewrite,
    // 저장하면 다시 받은 뒤 응답 값으로 상세를 다시 그린다. 고쳐 쓰기는 옛 거래가 지워져 돌아갈 상세가 없어 시트를 모두 닫는다
    onSaved: (updated) => setMarked(updated),
    onReplaced: onClose,
    onClose: () => setStep("detail"),
    onRewrite: (seed) => {
      setEditSeed({ rewrite: seed });
      form.beginEdit({ rewrite: seed });
    },
  });
  const formParts = useTxSheetParts(form, {
    mobile,
    embedded: true,
    onClose: () => setStep("detail"),
    onBack: () => setStep("detail"),
  });
  const startEdit = () => {
    setEditSeed({ expense });
    form.beginEdit({ expense });
    setStep("edit");
  };
  const categoriesQ = useExpenseCategories({ silent: true });
  const assetsQ = useAssets({ silent: true });
  const splitsQ = useExpenseSplits(expense.rowId);
  const recurringsQ = useRecurringTransactions(undefined, { silent: true });
  const dutchPaysQ = useDutchPays({ silent: true });
  const loading = categoriesQ.isLoading || assetsQ.isLoading;

  const categories: ExpenseCategory[] = categoriesQ.data ?? [];
  const linkedRecurring = (recurringsQ.data ?? []).filter(
    (r) => r.sourceExpenseRowId === expense.rowId,
  );
  const linkedDutchPays = (dutchPaysQ.data ?? []).filter(
    (d) => d.sourceExpenseRowId === expense.rowId,
  );
  const splits = splitsQ.data ?? [];
  const splitCount = splits.length;

  // 나누기 · 더치페이 · 반복 설정은 같은 표면 안 한 단계다(I-21 F · G · H). 단계를 열 때마다 처음 값으로 쌓는다
  const backToDetail = () => setStep("detail");
  const splitParts = useSplitStep({
    enabled: step === "split",
    expense,
    onSaved: backToDetail,
    onExit: backToDetail,
  });
  const dutchParts = useDutchStep({
    enabled: step === "dutch",
    expense,
    onCreated: backToDetail,
    onExit: backToDetail,
  });
  // 연결된 반복이 있으면 그 반복의 수정 폼, 없으면 거래 씨앗(새로 만들기). 둘 이상이면 시작일이 가장 늦은 하나(H 45)
  const [recurringTarget, setRecurringTarget] = useState<
    RecurringTransaction | undefined
  >();
  const [recurringGen, setRecurringGen] = useState(0);
  const confirmFail = useConfirmFail();
  const unconfirmedSnack = useUnconfirmedSnack();
  const openingRecurring = useRef(false);
  const openRecurringWith = (list: RecurringTransaction[]) => {
    const latest = list
      .filter((r) => r.sourceExpenseRowId === expense.rowId)
      .sort((a, b) => (b.startDate ?? "").localeCompare(a.startDate ?? ""))[0];
    setRecurringTarget(latest);
    setRecurringGen((g) => g + 1);
    setStep("recurring");
  };
  // 반복 목록을 받기 전 · 실패 중에는 연결 여부를 모른다 — 새로 만들기를 열면 같은 거래에 반복이 하나 더 생긴다.
  // 받아 온 뒤 정하고, 못 받으면 열지 않고 실패 스낵바 + [다시 시도]
  const openRecurring = async () => {
    if (openingRecurring.current) return;
    openingRecurring.current = true;
    try {
      const load = async () => {
        const r = recurringsQ.data
          ? { data: recurringsQ.data }
          : await recurringsQ.refetch();
        if (!r.data) throw new Error("recurring list");
        return r.data;
      };
      let list: RecurringTransaction[];
      try {
        list = await load();
      } catch (error) {
        confirmFail({
          error,
          message: t("txDetail.recurringLoadFailed"),
          retry: async () => {
            const r = await recurringsQ.refetch();
            if (!r.data) throw new Error("recurring list");
            return r.data;
          },
          onRetried: () => openRecurringWith(recurringsQ.data ?? []),
        });
        return;
      }
      openRecurringWith(list);
    } finally {
      openingRecurring.current = false;
    }
  };
  const recurringForm = useRecurringForm({
    expenseSeed: expense,
    recurring: recurringTarget,
    resetKey: recurringGen,
    onClose: backToDetail,
  });
  const recurringParts = useRecurringStepParts(recurringForm, backToDetail);
  const focusRecurringAmount = recurringForm.focusAmount;
  useEffect(() => {
    // 새 폼은 첫 칸(금액)에 초점, 연결된 반복의 수정 폼은 키보드 없이 표면
    if (step !== "recurring" || recurringTarget) return;
    const id = requestAnimationFrame(focusRecurringAmount);
    return () => cancelAnimationFrame(id);
  }, [step, recurringTarget, focusRecurringAmount]);
  const stepParts =
    step === "split"
      ? splitParts
      : step === "dutch"
        ? dutchParts
        : step === "recurring"
          ? recurringParts
          : null;

  const category = categories.find((c) => c.rowId === expense.categoryRowId);
  const parent = category?.parentRowId
    ? categories.find((c) => c.rowId === category.parentRowId)
    : undefined;
  const asset: Asset | undefined = (assetsQ.data?.assets ?? []).find(
    (a) => a.rowId === expense.assetRowId,
  );

  const isIncome = expense.expenseType === "INCOME";
  // 종류는 부호가 아니라 타입으로 — 환불이 음수 지출이라 부호로 가르면 수입으로 샌다.
  const txKind = kindOfExpense(expense.expenseType);
  const sign = isIncome ? "+" : MINUS;

  // 같은 가맹점의 같은 달 거래 (상세 제외)
  const merchantKey = expense.merchant?.trim() ?? "";
  const [yStr, mStr] = (expense.expenseDate ?? "").slice(0, 7).split("-");
  const year = Number(yStr);
  const month = Number(mStr);
  const pad = (n: number) => String(n).padStart(2, "0");
  const startDate = year && month ? `${year}-${pad(month)}-01` : undefined;
  const endDate =
    year && month
      ? `${year}-${pad(month)}-${pad(new Date(year, month, 0).getDate())}`
      : undefined;
  const historyQ = useSearchExpenses(
    merchantKey ? { merchant: merchantKey, startDate, endDate } : {},
    { silent: true },
  );
  // 카테고리 · 계좌 · 연결 반복 · 더치페이 목록은 이름 · 연결 표시를 채운다 — 값 없이 실패하면 한 자리에서 말한다
  // (상세는 시트라 공용 참조 스낵바가 쉰다 — useHoldReferenceNotice)
  const relatedFailed = [categoriesQ, assetsQ, recurringsQ, dutchPaysQ].some(
    (q) => q.isError && !q.data,
  );
  const retryRelated = () => {
    for (const q of [categoriesQ, assetsQ, recurringsQ, dutchPaysQ])
      if (q.isError) void q.refetch();
  };
  const others = (historyQ.data ?? [])
    .filter((tx) => tx.rowId !== expense.rowId)
    .sort((a, b) => b.expenseDate.localeCompare(a.expenseDate));
  const history = others.slice(0, 5);
  const historyGroups = (() => {
    const m = new Map<string, Expense[]>();
    for (const tx of history) {
      const k = toDayKey(tx.expenseDate);
      const arr = m.get(k);
      if (arr) arr.push(tx);
      else m.set(k, [tx]);
    }
    return [...m.entries()];
  })();
  // 머리 숫자는 이 달 전체(이 거래 포함) — 줄은 최대 5 개라 넘으면 보조 글이 말한다
  const merchantMonthCount = historyQ.data?.length ?? 0;
  // 환불된 거래는 합계에서 뺀다 — 환불 안내("합계에서 빠져요")와 머리 숫자가 어긋나지 않게
  const merchantMonthTotal = (historyQ.data ?? []).reduce(
    (s, tx) => (tx.refundedAt ? s : s + Math.abs(tx.amount)),
    0,
  );

  const day = toDayKey(expense.expenseDate);
  const today = todayLocalKey();
  const paymentMethodLabel = (() => {
    switch (expense.paymentMethod) {
      case "CASH":
        return t("form.paymentMethod.CASH");
      case "CARD":
        return t("form.paymentMethod.CARD");
      case "TRANSFER":
        return t("paymentTransferFull");
      case "OTHER":
        return t("form.paymentMethod.OTHER");
      default:
        return null;
    }
  })();

  // 카드면 확인창이 한 줄 더 말한다 — 이미 낸 돈이 어디로 가는지가 사용자의 관심사다.
  const isCreditCard = asset?.assetType === "CREDIT_CARD";
  const cardHasPaymentAsset = asset?.paymentAssetRowId != null;
  /** [잔액 고치기]가 여는 결제계좌 — 결제계좌 없는 카드는 고칠 통장이 없다(D9). */
  const paymentAssetRowId = isCreditCard
    ? (asset?.paymentAssetRowId ?? null)
    : null;
  /** 결제가 끝난 회차의 카드 거래인가(D1) — 거래 날짜와 카드의 `cardClosedThrough` 만 견준다. */
  const closedSpan = isCreditCard
    ? closedCycleSpan(
        expense.expenseDate,
        expense.installmentMonths,
        asset?.cardClosedThrough,
      )
    : null;
  const resultContext = { closed: closedSpan != null, paymentAssetRowId };

  // 시스템이 만든 거래(매도 실현손익·이체 이자·카드 이월)는 원본을 지워야 사라진다.
  const isAutoGenerated = expense.autoSource != null;
  const isRefunded = isRefundedTx(expense);
  // 기록만 — 결제가 끝난 회차에 뒤늦게 적은 카드 지출(닫힌 회차 R2). 할부는 지난 회차분만 기록용이라 금액이 거래보다 작으면 "이 중 N원" 으로 말한다.
  const recordOnlyAmount =
    !isRefunded && expense.cardSettledThrough != null
      ? (expense.recordOnlyAmount ?? Math.abs(expense.amount))
      : null;

  const displayMerchant =
    expense.merchant ??
    expense.description ??
    category?.categoryName ??
    expense.categoryName ??
    t("transaction");

  const runDelete = () => {
    // 실패는 서버 글 대신 고정 글 — 확인창을 닫고 스낵바 + [다시 시도](같은 요청을 바로, 28-3)
    deleteMut.mutate(
      { id: expense.rowId, silent: true },
      {
        onSuccess: (result) => {
          // 미리 낸 돈이 돌아왔으면 그 금액을, 닫힌 회차였으면 [잔액 고치기]를(D4·D9).
          notifyResult(result, resultContext);
          setConfirmDelete(false);
          onClose();
        },
        onError: (error) => {
          setConfirmDelete(false);
          if (unconfirmedSnack(error, "delete")) return;
          snackbar.show({
            message: t("txDetail.deleteFailed"),
            tone: "critical",
            action: { label: tc("retry"), onClick: runDelete },
          });
        },
      },
    );
  };

  const runCancelRefund = () => {
    cancelRefundMut.mutate(
      { id: expense.rowId, silent: true },
      {
        onSuccess: (updated) => {
          setMarked(updated);
          setConfirmCancelRefund(false);
        },
        onError: (error) => {
          setConfirmCancelRefund(false);
          // 결과를 확인하지 못했으면 실패라 하지 않고 [다시 시도] 도 두지 않는다(두 번 될 수 있다) — 환불 취소는 "처리"
          if (unconfirmedSnack(error, "action")) return;
          snackbar.show({
            message: t("txDetail.refundCancelFailed"),
            tone: "critical",
            action: { label: tc("retry"), onClick: runCancelRefund },
          });
        },
      },
    );
  };

  const runRefund = () => {
    setRefundFailed(false);
    refundMut.mutate(
      {
        id: expense.rowId,
        // 날짜만 고르므로 시각은 정오로 둔다 — 자정으로 보내면 그날 앞에 찍힌 거래보다 과거가 되어 카드 회차 판정이 하루 밀린다.
        refundedAt: refundDate ? `${refundDate}T12:00:00` : undefined,
        silent: true,
      },
      {
        // 응답은 목록을 다시 받은 뒤에 온다 — 상세로 돌아오면 새 값(환불됨 Callout)이 바로 보인다
        onSuccess: (updated) => {
          setMarked(updated);
          setStep("detail");
          notifyResult(updated, resultContext);
        },
        onError: () => setRefundFailed(true),
      },
    );
  };

  const canRefund =
    !isIncome &&
    !isRefunded &&
    !isAutoGenerated &&
    isRefundableDate(expense.expenseDate, today);

  const moreRows: MoreRow[] = [
    ...(canRefund
      ? [
          {
            key: "refund",
            icon: <Undo2 aria-hidden />,
            label: t("txDetail.refund"),
            onClick: () => {
              setRefundDate(today);
              setRefundFailed(false);
              refundMut.reset();
              setStep("refund");
            },
          },
        ]
      : []),
    // 분할도 환불된 거래·시스템이 만든 거래에는 안 띄운다 — 서버가 막는다
    ...(isRefunded || isAutoGenerated
      ? []
      : [
          {
            key: "split",
            icon: <Scissors aria-hidden />,
            label: t("splitTitle"),
            value:
              splitCount > 0
                ? t("txDetail.splitValue", { count: splitCount })
                : null,
            onClick: () => setStep("split"),
          },
        ]),
    // 자동으로 만들어진 거래는 반복·더치페이의 원본이 될 수 없다 — 숨기지 않고 막힌 줄로(서버도 EXP_050)
    {
      key: "recurring",
      icon: <Repeat aria-hidden />,
      label: t("txDetail.recurring"),
      value: linkedRecurring.length > 0 ? t("txDetail.linked") : null,
      disabled: isAutoGenerated,
      onClick: () => void openRecurring(),
    },
    {
      key: "dutch",
      icon: <Users aria-hidden />,
      label: t("txDetail.dutchPay"),
      value:
        linkedDutchPays.length > 0
          ? t("txDetail.countCases", { count: linkedDutchPays.length })
          : null,
      disabled: isAutoGenerated,
      onClick: () => setStep("dutch"),
    },
  ];

  const title = isIncome
    ? t("txDetail.incomeTitle")
    : t("txDetail.expenseTitle");

  const editing = step === "edit";
  const ep = formParts.embedParts;

  const inRefund = step === "refund";
  const refundDirty = inRefund && refundDate !== today;
  const footer = inRefund
    ? {
        primary: {
          label: t("txDetail.refundConfirm"),
          onClick: runRefund,
          loading: refundMut.isPending,
        },
        cancelLabel: tc("cancel"),
      }
    : !isExpenseDeletable(expense)
      ? undefined
      : {
          onDelete: () => setConfirmDelete(true),
          deleting: deleteMut.isPending,
          // 환불된 거래·시스템이 만든 거래는 고칠 수 없다 — 돈이 이미 자산으로 돌아가 있어 되돌릴 기준이 사라진다(서버도 EXP_043).
          // 자동 생성이어도 서버가 지울 수 있다고 하면(만든 증권 자산이 삭제됨) 삭제만 남는다.
          primary:
            isRefunded || isAutoGenerated
              ? undefined
              : { label: tc("edit"), onClick: startEdit },
        };

  return (
    <>
      <DetailSurface
        title={
          stepParts
            ? stepParts.title
            : editing
              ? ep.title
              : inRefund
                ? t("txDetail.refundConfirmTitle")
                : title
        }
        onClose={onClose}
        subStep={inRefund || editing || stepParts != null}
        dirty={stepParts ? stepParts.dirty : editing ? ep.dirty : refundDirty}
        closeDirty={
          stepParts ? stepParts.dirtyAll : editing ? ep.dirtyAll : undefined
        }
        busy={
          (editing && form.submitting) ||
          (inRefund && refundMut.isPending) ||
          (stepParts?.busy ?? false)
        }
        onStepBack={
          stepParts
            ? stepParts.onBack
            : editing
              ? ep.onBack
              : () => {
                  setStep("detail");
                  refundMut.reset();
                }
        }
        footer={editing || stepParts ? undefined : footer}
        footerNode={
          stepParts ? stepParts.footer : editing ? ep.footer : undefined
        }
        footerAbove={
          stepParts ? stepParts.above : editing ? ep.above : undefined
        }
        bodyRef={
          stepParts ? stepParts.bodyRef : editing ? ep.bodyRef : undefined
        }
        // 값 하나를 치는 단계는 닫기 원 자리에 "완료" — 표면 경계는 1280(시트는 768 ~ 1279 포함)이라 mobile 로 가르지 않는다
        stepDone={
          stepParts ? (
            stepParts.inSub ? (
              <SheetStepDone onClick={stepParts.onDone} />
            ) : undefined
          ) : editing && ep.inSub ? (
            <SheetStepDone onClick={ep.onDone} />
          ) : undefined
        }
        bodyKey={
          stepParts
            ? `${step}:${stepParts.inSub ? 1 : 0}:${step === "recurring" ? recurringForm.step : ""}`
            : editing
              ? `edit:${form.main}:${form.sub ?? ""}:${form.openReconcile ? "r" : ""}${ep.inSub ? 1 : 0}`
              : step
        }
      >
        {stepParts ? (
          stepParts.body
        ) : editing ? (
          ep.body
        ) : inRefund ? (
          <>
            {refundFailed && (
              <div className="px-global-gutter pb-x2 pt-x1">
                <Callout tone="critical" role="alert">
                  {sft(refundMut.error, t("txDetail.refundFailed"))}
                </Callout>
              </div>
            )}
            <RefundStep
              amount={Math.abs(expense.amount)}
              kind={txKind}
              txDay={day}
              today={today}
              value={refundDate}
              onChange={setRefundDate}
              closedSpan={closedSpan}
              assetName={expense.assetName ?? asset?.assetName ?? null}
              cardNoPaymentAccount={isCreditCard && !cardHasPaymentAsset}
            />
          </>
        ) : loading ? (
          <TxDetailSkeleton />
        ) : (
          <>
            <DetailHeadBlock
              tile={
                <CategoryTile48
                  color={category?.color ?? expense.categoryColor ?? null}
                  icon={category?.icon ?? expense.categoryIcon ?? null}
                />
              }
              name={displayMerchant}
              amount={
                <AmountText amount={expense.amount} sign={sign} kind={txKind} />
              }
              amountClassName={isIncome ? "text-fg-brand" : undefined}
              dateTime={dateTimeLabel(expense.expenseDate)}
            />

            {/* 상태 Callout — 환불됨 · 기록만 · 자동 거래 */}
            {isRefunded && (
              <RefundedCallout
                text={t("txDetail.refundedAt", {
                  date: formatDateSmart(toDayKey(expense.refundedAt)),
                })}
                // 결제가 끝난 회차의 환불은 통계에서만 빠진다(D1·U5) — 결제계좌 잔액을 고쳐 맞춘다(D9)
                onFixBalance={
                  closedSpan != null && paymentAssetRowId != null
                    ? () => navigate(editAssetPath(paymentAssetRowId))
                    : undefined
                }
                onCancel={() => setConfirmCancelRefund(true)}
                cancelling={cancelRefundMut.isPending}
              />
            )}
            {recordOnlyAmount != null && (
              <RecordOnlyCallout>
                {recordOnlyAmount < Math.abs(expense.amount) ? (
                  <RecordOnlyPart amount={recordOnlyAmount} kind={txKind} />
                ) : (
                  t("txDetail.recordOnlyNote")
                )}
              </RecordOnlyCallout>
            )}
            {isAutoGenerated && (
              <AutoGeneratedCallout
                text={t(`addTx.autoSource.${expense.autoSource}`, {
                  defaultValue: t("addTx.autoSource.default"),
                })}
              />
            )}

            {/* 값 줄 — 키-값. 값이 없는 줄은 그리지 않는다. 금액 · 날짜 줄은 머리에 있다 */}
            <List data-slot="tx-detail-kv">
              <KvRow
                label={t("category")}
                value={
                  category
                    ? parent
                      ? `${parent.categoryName} · ${category.categoryName}`
                      : category.categoryName
                    : (expense.categoryName ?? t("txDetail.uncategorized"))
                }
              />
              {expense.originalCurrency && expense.originalAmount != null && (
                <KvRow
                  label={t("txDetail.foreignPayment")}
                  value={`${formatOriginalAmount(
                    expense.originalAmount,
                    expense.originalCurrency,
                    i18n.language,
                  )}${
                    expense.exchangeRate != null
                      ? ` × ${expense.exchangeRate.toLocaleString(i18n.language)}`
                      : ""
                  }`}
                />
              )}
              <KvRow
                label={t("paymentMethodLabel")}
                value={paymentMethodLabel}
              />
              <KvRow
                label={t("accountCard")}
                value={
                  asset
                    ? asset.institution && asset.institution !== asset.assetName
                      ? `${asset.institution} · ${asset.assetName}`
                      : asset.assetName
                    : expense.assetName
                }
              />
              <KvRow label={t("memo")} value={expense.description} />
            </List>

            <MoreSection rows={moreRows} />

            {splitCount > 0 && !loadFailed(splitsQ) && (
              <SplitSection
                expense={expense}
                splits={splits}
                categories={categories}
                kind={txKind}
                sign={sign}
              />
            )}
            {splitsQ.isLoading && <SplitSkeleton />}
            {loadFailed(splitsQ) && (
              <SplitFailure
                onRetry={() => void splitsQ.refetch()}
                retrying={splitsQ.isFetching}
              />
            )}

            {merchantKey && historyQ.isError && !historyQ.data && (
              <BandFailure
                title={tc("query.failedNamed", {
                  name: t("txDetail.historyName"),
                })}
                onRetry={() => void historyQ.refetch()}
              />
            )}
            {relatedFailed && (
              <BandFailure
                title={tc("query.failedNamed", {
                  name: t("txDetail.relatedName"),
                })}
                onRetry={retryRelated}
              />
            )}
            {merchantKey && history.length > 0 && (
              <HistorySection
                merchantMonthCount={merchantMonthCount}
                merchantMonthTotal={merchantMonthTotal}
                sign={sign}
                kind={txKind}
                groups={historyGroups}
                overflow={others.length > 5}
              />
            )}
          </>
        )}
      </DetailSurface>

      {confirmDelete && (
        <ConfirmDialog
          title={t("deleteConfirm.title")}
          message={
            <>
              {t("txDetail.deleteMessage", { name: displayMerchant })}
              {/* 결제가 끝난 회차의 카드 거래는 지워도 통장이 그대로다(D1) — 그걸 여기서 말한다. */}
              <ClosedCycleNote span={closedSpan} />
            </>
          }
          confirmLabel={tc("delete")}
          danger
          loading={deleteMut.isPending}
          onCancel={() => !deleteMut.isPending && setConfirmDelete(false)}
          onConfirm={runDelete}
        />
      )}

      {confirmCancelRefund && (
        <ConfirmDialog
          title={t("txDetail.refundCancel")}
          message={
            // 옛 환불이 만든 환급 이체가 묶여 있으면 그 이체도 되돌아간다. 그 밖은 표식만 걷히므로 "환급된 금액" 을 말하면 거짓이 된다.
            expense.refundTransferRowId != null ? (
              t("txDetail.refundCancelConfirmTransfer")
            ) : (
              <>
                {t("txDetail.refundCancelConfirm")}
                <ClosedCycleNote span={closedSpan} />
              </>
            )
          }
          confirmLabel={t("txDetail.refundCancel")}
          loading={cancelRefundMut.isPending}
          onCancel={() =>
            !cancelRefundMut.isPending && setConfirmCancelRefund(false)
          }
          onConfirm={runCancelRefund}
        />
      )}

      {editing && formParts.overlays}
    </>
  );
}

/** "이 중 N원은 결제가 끝난 회차분이라 기록만 남았어요…" — 금액 가리기를 따른다 */
function RecordOnlyPart({
  amount,
  kind,
}: {
  amount: number;
  kind: ReturnType<typeof kindOfExpense>;
}) {
  const { t } = useTranslation("expense");
  return (
    <Trans
      t={t}
      i18nKey="txDetail.recordOnlyPartNote"
      values={{
        amount: `${wonPre()}${KRW(amount)}${isEn() ? "" : "원"}`,
      }}
      components={{
        amt: (
          <MaskAmount card="ledger.txDetail" kind={kind}>
            {""}
          </MaskAmount>
        ),
      }}
    />
  );
}
