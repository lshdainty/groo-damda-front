export interface MoreRow {
  key: string;
  icon: ReactNode;
  label: string;
  /** 연결 수 글 — "연결됨" · "3건" · "2개로 나눔". 없으면 값 글 없음 */
  value?: string | null;
  /** 막힌 줄 — 누름 · 호버 없음, 제목 · 아이콘 fg-disabled, 꺾쇠 없음 */
  disabled?: boolean;
  onClick: () => void;
}

/** "더 하기" 동작 줄 (I-21 B 10) */
export function MoreSection({ rows }: { rows: MoreRow[] }) {
  const { t } = useTranslation("expense");
  if (rows.length === 0) return null;
  return (
    <>
      <ListTitleBar>{t("txDetail.moreTitle")}</ListTitleBar>
      <List data-slot="tx-detail-more">
        {rows.map((r) => (
          <ListButtonItem
            key={r.key}
            data-testid={`more-${r.key}`}
            prefix={
              <span className="inline-flex size-[22px] items-center justify-center text-fg-neutral [&>svg]:size-[22px]">
                {r.icon}
              </span>
            }
            title={r.label}
            disabled={r.disabled}
            aria-disabled={r.disabled || undefined}
            suffix={
              r.disabled ? undefined : (
                <>
                  {r.value}
                  <ChevronRight
                    aria-hidden
                    size={18}
                    className="text-fg-neutral-subtle"
                  />
                </>
              )
            }
            onClick={r.disabled ? undefined : r.onClick}
          />
        ))}
      </List>
    </>
  );
}

function splitTone(categories: ExpenseCategory[], id: number) {
  const cat = categories.find((c) => c.rowId === id);
  const parent = cat?.parentRowId
    ? categories.find((c) => c.rowId === cat.parentRowId)
    : undefined;
  return { cat, parent };
}

/** "내역 분할 n개" 묶음 — 접지 않는다. 막대 + 줄(누르지 않는다) (I-21 B 11) */
export function SplitSection({
  expense,
  splits,
  categories,
  kind,
  sign,
}: {
  expense: Expense;
  splits: ExpenseSplit[];
  categories: ExpenseCategory[];
  kind: HideKind;
  sign: string;
}) {
  const { t } = useTranslation("expense");
  const total = Math.abs(expense.amount);
  return (
    <>
      <ListTitleBar
        right={
          <span className="text-t4 font-bold">
            {t("txDetail.splitSum")}{" "}
            <MaskAmount card="ledger.txDetail" kind={kind}>
              {withCommaBreaks(KRW(total))}
            </MaskAmount>
            <HideUnit card="ledger.txDetail" kind={kind}>
              {isEn() ? "" : "원"}
            </HideUnit>
          </span>
        }
      >
        {t("txDetail.splitHeader", { count: splits.length })}
      </ListTitleBar>
      <div
        data-slot="tx-detail-split-bar"
        aria-hidden
        className="mx-global-gutter mb-x2 flex h-x2 overflow-hidden rounded-full bg-bg-neutral-weak"
      >
        {splits.map((s) => {
          const ratio = total > 0 ? s.amount / total : 0;
          const { cat } = splitTone(categories, s.categoryRowId);
          return ratio > 0 ? (
            <span
              key={s.rowId}
              style={{
                width: `${ratio * 100}%`,
                background: getPaletteByColor(cat?.color).color,
              }}
            />
          ) : null;
        })}
      </div>
      <List data-slot="tx-detail-splits">
        {splits.map((s) => {
          const { cat, parent } = splitTone(categories, s.categoryRowId);
          const pal = getPaletteByColor(cat?.color);
          const pct = total > 0 ? (s.amount / total) * 100 : 0;
          return (
            <ListItem
              key={s.rowId}
              prefix={
                <ListTile
                  aria-hidden
                  style={{ background: pal.bg, color: pal.color }}
                >
                  <Icon name={cat?.icon || "tag"} size={20} />
                </ListTile>
              }
              title={
                s.label && s.label.trim()
                  ? s.label
                  : (s.categoryName ?? t("item"))
              }
              detail={
                <TagGroup size="t3" truncate>
                  {parent && (
                    <TagGroupItem shrink={0}>
                      {parent.categoryName}
                    </TagGroupItem>
                  )}
                  <TagGroupItem shrink={0}>
                    {s.categoryName ?? "-"}
                  </TagGroupItem>
                  <TagGroupItem shrink={0}>
                    {formatPercent(pct, "share")}
                  </TagGroupItem>
                </TagGroup>
              }
              suffix={
                <span className="whitespace-nowrap font-bold tabular-nums text-fg-neutral">
                  <MaskAmount card="ledger.txDetail" kind={kind}>
                    {sign}
                    {withCommaBreaks(KRW(s.amount))}
                  </MaskAmount>
                  <HideUnit card="ledger.txDetail" kind={kind}>
                    {isEn() ? "" : "원"}
                  </HideUnit>
                </span>
              }
            />
          );
        })}
      </List>
    </>
  );
}

