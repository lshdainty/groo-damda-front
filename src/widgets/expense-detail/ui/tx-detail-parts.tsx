export function RefundedCallout({
  text,
  onFixBalance,
  onCancel,
  cancelling,
}: {
  text: string;
  /** 결제가 끝난 회차 + 결제계좌가 있을 때만 */
  onFixBalance?: () => void;
  onCancel: () => void;
  cancelling: boolean;
}) {
  const { t } = useTranslation("expense");
  return (
    <StatusSlot>
      <Callout tone="neutral" icon={<Undo2 aria-hidden />}>
        {text}
        <span className="mt-x2 flex flex-wrap gap-x2">
          {onFixBalance && (
            <Button
              variant="neutralOutline"
              size="small"
              onClick={onFixBalance}
            >
              {t("closedCycle.fixBalance")}
            </Button>
          )}
          <Button
            variant="neutralOutline"
            size="small"
            loading={cancelling}
            onClick={onCancel}
          >
            {t("txDetail.refundCancel")}
          </Button>
        </span>
      </Callout>
    </StatusSlot>
  );
}

/**
 * 키-값 줄 — 열쇠 t5 `fg-neutral`, 값은 줄 끝 오른쪽 맞춤(`fg-neutral-muted`, 줄이 몇 줄이든 text-end — 값 맞춤 규칙).
 * 값이 없으면 그리지 않는다(I-20 C 18).
 */
export function KvRow({ label, value }: { label: string; value: ReactNode }) {
  if (value == null || value === "") return null;
  return (
    <ListItem
      title={label}
      suffixText
      suffix={
        <span className="block text-end text-fg-neutral-muted [overflow-wrap:anywhere]">
          {value}
        </span>
      }
    />
  );
}

