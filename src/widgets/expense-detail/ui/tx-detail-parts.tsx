/** "−128,000,000원" — 쉼표 뒤에서만 줄을 바꾸고, 금액 가리기를 따른다 */
export function AmountText({
  amount,
  sign,
  card = "ledger.txDetail",
  kind,
  currency,
}: {
  amount: number;
  /** "−" · "+" · "" */
  sign: string;
  card?: ComponentProps<typeof MaskAmount>["card"];
  kind?: HideKind;
  /** 금액의 통화 — 외화면 "$1,000.00"(이체는 보내는 계좌 통화, I-13). 없으면 원화 */
  currency?: string | null;
}) {
  if (isForeignCurrency(currency)) {
    return (
      <MaskAmount card={card} kind={kind}>
        {withCommaBreaks(
          `${sign}${formatAssetAmount(Math.abs(amount), currency!, dsLocale())}`,
        )}
      </MaskAmount>
    );
  }
  return (
    <>
      <MaskAmount card={card} kind={kind}>
        {withCommaBreaks(`${sign}${wonPre()}${KRW(amount, { abs: true })}`)}
      </MaskAmount>
      <HideUnit card={card} kind={kind}>
        {isEn() ? "" : "원"}
      </HideUnit>
    </>
  );
}

