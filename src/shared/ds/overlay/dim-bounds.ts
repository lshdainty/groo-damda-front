/*
 * 딤이 덮는 범위 — 시트(Menu Sheet 포함) · 대화상자 · 확인창의 딤에 쓴다. 딤은 "뒤 화면 전체"다(bottom-sheet.md · dialog.md ·
 * alert-dialog.md 의 ⓐ Overlay).
 *
 * `fixed inset-0`(레이아웃 뷰포트)만 덮으면 iPhone Safari 26 에서 키보드가 뜬 동안 레이아웃 뷰포트 아래 띠 — 떠 있는 주소 알약 ·
 * 입력 도구줄 둘레에서 키보드 윗변까지 — 에 뒤 페이지가 흐림 없이 비친다. 딤에 붙인 ::after(#616)도, body 끝의 absolute 거울(#620)도
 * 그 띠를 칠하지 못했다. 레이아웃 좌표로 띠 자리를 계산해 맞추는 것도 안 된다 — 계산상 딤 안인데 흰색인 상태가 있었다. 칠한 것은
 * fixed 인 상자 자체를 화면 위아래로 넉넉히 넘치게 둔 것뿐이다 — 띠 · 입력 도구줄 뒤 · 키보드 윗변의 둥근 부분까지 덮였다
 * (2026-11-17 QA 실기기 · iPhone 17 Pro · Safari 26 — top −2000 · 높이 6000 층).
 *
 * 그래서 딤 상자를 화면 높이(lvh — 주소창이 접혔을 때의 가장 큰 화면)만큼 위아래로 넘친다. 띠는 화면 안이라 lvh 하나면 넉넉하다.
 * 키보드와 상관없이 늘 이렇게 둔다 —
 *   - 넘친 부분은 화면 밖이라 보이지도 눌리지도 않는다. 위아래가 같은 만큼 넘쳐 가운데도 그대로다.
 *   - fixed 는 문서의 스크롤 범위를 늘리지 않는다(열린 동안은 문서 스크롤도 잠겨 있다). 카탈로그 무대는 넘친 것을 잘라 보인다.
 *   - 키보드가 올라오는 동안(크기 이벤트가 오기 전)에도 이미 덮여 있다.
 * vaul 은 딤에 투명도 · 전환만 인라인으로 넣는다 — 자리(top · bottom · height)는 건드리지 않는다.
 *
 * 이 넘침으로 띠 둘레(알약 · 도구줄 뒤 · 키보드 윗변의 둥근 부분)는 덮인다. 다만 키보드 위 띠 자체는 Safari 가 body 의 바탕색으로
 * 칠해 fixed 층이 어떤 크기로도 닿지 않는 경우가 있다(2026-11-18 QA 실기기 — 도구줄만 뜬 상태 · 알약과 함께 뜬 상태 모두) — 그 띠는
 * 딤이 열린 동안 body 바탕색을 딤 토큰으로 두는 src/index.css 규칙이 맡는다.
 *
 * Tailwind 는 소스의 글자 그대로를 읽으므로 클래스를 나눠 잇지 않는다.
 */
